/**
 * Captures the README's screenshots against a real running app.
 *
 *   node e2e/capture-screenshots.mjs
 *
 * Needs the dev servers up (web :3000, api :4000) and the API started with
 * EXTRACTION_ALLOW_PRIVATE_ADDRESSES=true, because it populates the library
 * from the e2e fixture server rather than the public internet -- the same
 * reasoning as the test suite (see e2e/helpers.ts): deterministic content,
 * no dependency on a page anyone can edit, and it runs offline.
 *
 * Everything happens in local/anonymous mode. That is not a shortcut: it
 * means no account is created, nothing touches a real user's data, and the
 * screenshots can be regenerated by anyone who clones the repo without
 * seeding a database first.
 *
 * Set PLAYWRIGHT_CHROMIUM_EXECUTABLE if the installed browser's build
 * number is not the one Playwright expects.
 */
import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
import path from "node:path";

const OUT = path.resolve(process.cwd(), "..", "..", ".github", "assets");
const FIXTURES = "http://127.0.0.1:4321";
const BASE = "http://localhost:3000";

// Deliberately a plausible reading list rather than "Test Article 1..5" --
// a screenshot of placeholder data advertises placeholder software.
const ARTICLES = [
  `${FIXTURES}/demo/attention.html`,
  `${FIXTURES}/demo/typography.html`,
  `${FIXTURES}/demo/spacing.html`,
  `${FIXTURES}/demo/archives.html`,
];

mkdirSync(OUT, { recursive: true });

const shot = async (page, name, opts = {}) => {
  await page.waitForTimeout(700);
  await page.screenshot({ path: path.join(OUT, `${name}.png`), ...opts });
  console.log("captured", name);
};

const browser = await chromium.launch({
  executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined,
});
// 2x so the images stay sharp on the retina displays most people read
// GitHub on; the README scales them down with a width attribute.
// 820 rather than 900: the library and review pages are short, and a tall
// viewport pads every screenshot with dead background that reads as an empty
// app rather than a calm one.
const page = await browser.newPage({ viewport: { width: 1440, height: 820 }, deviceScaleFactor: 2 });

async function save(url) {
  await page.goto(`${BASE}/library`);
  await page.getByRole("button", { name: /save article/i }).click();
  await page.getByPlaceholder(/example\.com/).fill(url);
  await page.getByRole("button", { name: /^save$/i }).click();
  await page.getByRole("heading", { name: /save an article/i }).waitFor({ state: "hidden", timeout: 30_000 });
}

for (const url of ARTICLES) await save(url);

await page.goto(`${BASE}/library`);
await shot(page, "library");

// Reader, with a highlight already made so the screenshot shows the feature
// rather than an empty page of prose.
await page.locator("a[href^='/reader/']").first().click();
await page.waitForURL(/\/reader\//);
const para = page.locator("[data-article-content] p").first();
await para.waitFor({ state: "visible", timeout: 20_000 });
await para.evaluate((el) => {
  const node = el.firstChild;
  const range = document.createRange();
  range.setStart(node, 0);
  range.setEnd(node, Math.min(90, node.textContent.length));
  const sel = window.getSelection();
  sel.removeAllRanges();
  sel.addRange(range);
  el.dispatchEvent(new MouseEvent("mouseup", { bubbles: true }));
});
await page.waitForTimeout(400);
await shot(page, "reader-highlight");

await page.getByTitle("Yellow").click();
await page.waitForTimeout(400);
await shot(page, "reader");

await page.goto(`${BASE}/highlights`);
await shot(page, "highlights");

// Daily Review twice, because the two states are the feature. Without a
// prompt it shows the passage and asks whether you remembered it; with one
// it asks the question and withholds both the passage and the grade buttons
// until you answer. A screenshot of only the first sells the wrong product.
await page.goto(`${BASE}/resurface`);
await shot(page, "daily-review");

await page.goto(`${BASE}/highlights`);
await page.getByRole("button", { name: "+ Add a recall prompt" }).first().click();
await page.getByPlaceholder(/Ask a question/i).fill("What does a link actually promise, and who promised it?");
await page.getByRole("button", { name: "Save", exact: true }).click();
await page.waitForTimeout(500);

await page.goto(`${BASE}/resurface`);
await shot(page, "daily-review-prompt");

await page.goto(`${BASE}/settings`);
await shot(page, "settings");

await browser.close();
console.log(`\nWrote to ${OUT}`);
